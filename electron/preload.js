const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getOverview: () => ipcRenderer.invoke('hw:overview'),
  getLive: () => ipcRenderer.invoke('hw:live'),
  getSoftware: () => ipcRenderer.invoke('sw:list'),
  openAppFolder: (key) => ipcRenderer.invoke('sw:openFolder', key),
  getProcesses: () => ipcRenderer.invoke('proc:list'),
  endTasks: (pids) => ipcRenderer.invoke('proc:end', pids),
  getStartup: () => ipcRenderer.invoke('startup:list'),
  setStartup: (id, enabled) => ipcRenderer.invoke('startup:set', id, enabled),
  scanCleanup: () => ipcRenderer.invoke('clean:scan'),
  deleteCleanup: (ids) => ipcRenderer.invoke('clean:delete', ids),
  getAppUpdates: () => ipcRenderer.invoke('apps:updates'),
  searchApps: (query) => ipcRenderer.invoke('apps:search', query),
  getAppDetails: (id) => ipcRenderer.invoke('apps:details', id),
  installApp: (id) => ipcRenderer.invoke('apps:install', id),
  upgradeApp: (id) => ipcRenderer.invoke('apps:upgrade', id),
  uninstallApp: (key) => ipcRenderer.invoke('sw:uninstall', key),
  scanLeftovers: (key) => ipcRenderer.invoke('sw:leftovers', key),
  scanLeftoversByName: (name, publisher) => ipcRenderer.invoke('left:scanName', name, publisher),
  removeLeftovers: (ids) => ipcRenderer.invoke('left:remove', ids),
  revealLeftover: (id) => ipcRenderer.invoke('left:reveal', id),
  openBackupFolder: () => ipcRenderer.invoke('left:openBackups'),
  getDrivers: () => ipcRenderer.invoke('drv:list'),
  scanDriverUpdates: () => ipcRenderer.invoke('drv:updates'),
  installDriverUpdate: (id) => ipcRenderer.invoke('drv:install', id),
  listBlocked: () => ipcRenderer.invoke('blk:list'),
  listBackups: () => ipcRenderer.invoke('bak:list'),
  restoreBackupKey: (id, index) => ipcRenderer.invoke('bak:restoreKey', id, index),
  restoreBackupFolder: (id, index) => ipcRenderer.invoke('bak:restoreFolder', id, index),
  deleteBackup: (id) => ipcRenderer.invoke('bak:delete', id),
  openBackup: (id) => ipcRenderer.invoke('bak:open', id),
  getDiskDrives: () => ipcRenderer.invoke('disk:drives'),
  getDiskStarts: () => ipcRenderer.invoke('disk:starts'),
  scanDiskStart: (key) => ipcRenderer.invoke('disk:scanStart', key),
  scanDiskChild: (id) => ipcRenderer.invoke('disk:scanChild', id),
  cancelDiskScan: () => ipcRenderer.invoke('disk:cancel'),
  revealDiskItem: (id) => ipcRenderer.invoke('disk:reveal', id),
  scanDownloads: (minMb) => ipcRenderer.invoke('dl:scan', minMb),
  trashDownloads: (ids) => ipcRenderer.invoke('dl:trash', ids),
  revealDownload: (id) => ipcRenderer.invoke('dl:reveal', id),
  listRecycleBin: () => ipcRenderer.invoke('bin:list'),
  emptyRecycleBin: () => ipcRenderer.invoke('bin:empty'),
  scanCaches: () => ipcRenderer.invoke('cache:scan'),
  clearCaches: (ids) => ipcRenderer.invoke('cache:clear', ids),
  openDriverLink: (key) => ipcRenderer.invoke('drv:open', key),
  setTheme: (mode) => ipcRenderer.invoke('ui:setTheme', mode),
});
